/**
 * Vocabulary of the user-facts layer (docs/planning/user-facts-layer.md). Pure — no DB, no LLM —
 * so the schema, the extraction contract, the store and the searchers share one source.
 *
 * A fact is one short statement about ONE person: the user, or someone in the user's life. The
 * extractor (an LLM) picks `kind` from this catalog and `subject` from the capture; code only
 * validates that the answer is in the catalog.
 */

/** What a fact is about. The LLM picks; the catalog is the ontology-style contract in the prompt. */
export const FACT_KINDS = [
  'preference',
  'dislike',
  'habit',
  'activity',
  'health',
  'circumstance',
  'relationship',
  'plan',
  'constraint',
  'trait',
] as const
export type FactKind = (typeof FACT_KINDS)[number]

/**
 * active = true now · superseded = replaced by a newer fact, kept as history (`superseded_by`) ·
 * forgotten = removed (a forget request, or its last source was archived or edited away): never
 * searched, never shown.
 */
export const FACT_STATUSES = ['active', 'superseded', 'forgotten'] as const
export type FactStatus = (typeof FACT_STATUSES)[number]

export const FACT_SUBJECT_KINDS = ['user', 'person'] as const
export type FactSubjectKind = (typeof FACT_SUBJECT_KINDS)[number]

/**
 * Who a fact is about, in words: "the user", or the person as the capture named them. A person
 * fact without a label is never presented as the user's.
 */
export function factSubjectLabel(subject: {
  subjectKind: FactSubjectKind
  subjectLabel: string | null
}): string {
  return subject.subjectKind === 'user' ? 'the user' : (subject.subjectLabel ?? 'a person')
}

/** What a secure value is (the label says which one, e.g. "licence plate"). */
export const SECURE_VALUE_KINDS = [
  'email',
  'phone',
  'postal_address',
  'licence_plate',
  'account_number',
  'id_number',
  'policy_number',
  'date_of_birth',
  'other',
] as const
export type SecureValueKind = (typeof SECURE_VALUE_KINDS)[number]

/** Facts the extractor is less sure of than this are not stored (Q2). */
export const FACT_CONFIDENCE_MIN = 0.7

/** A statement is one short sentence; a longer one is a contract violation, not something to cut. */
export const FACT_STATEMENT_MAX_CHARS = 500

/** Hard bound on the facts one capture can yield. */
export const FACT_EXTRACTION_MAX_FACTS = 12

/**
 * Where an identifier's value would stand in the statement the extractor writes. The extractor
 * never writes the value into the statement; code replaces this placeholder with the reference
 * token once the secure value has an id.
 */
export const SECURE_VALUE_PLACEHOLDER = '[secure value]'

const UUID = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'

/**
 * The reference an identifier fact's stored statement holds in place of the value:
 * `[secure:<user_secure_value.id>]`. It is what retrieval returns and what an answer model may
 * emit; the server substitutes the value into the user-facing response after generation, and only
 * when the user asked for it. Structural token generated by code, not a judgement about text.
 */
export function secureReferenceToken(secureValueId: string): string {
  return `[secure:${secureValueId}]`
}

/** Fresh matcher for every reference token in a text (capture group 1 = the secure value id). */
export function secureReferencePattern(): RegExp {
  return new RegExp(`\\[secure:(${UUID})\\]`, 'gi')
}

/**
 * The statement as every index and every LLM prompt sees it: reference tokens collapse to the
 * placeholder, so the embedding, the lexical surface and prompts carry no id and no value.
 */
export function statementForIndex(statement: string): string {
  return statement.replace(secureReferencePattern(), SECURE_VALUE_PLACEHOLDER)
}

/** Stored form of an identifier statement: the placeholder becomes the reference token. */
export function bindSecureReference(displayStatement: string, secureValueId: string): string {
  return displayStatement.split(SECURE_VALUE_PLACEHOLDER).join(secureReferenceToken(secureValueId))
}

/** How many placeholders a display statement holds. */
export function countSecurePlaceholders(displayStatement: string): number {
  return displayStatement.split(SECURE_VALUE_PLACEHOLDER).length - 1
}
